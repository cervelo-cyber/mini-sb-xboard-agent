// Multi-node: only vless/both entries get Reality keypairs; hy2 is untouched.
func TestRealityKeypairMultiNodeNodesJSON(t *testing.T) {
	dir := t.TempDir()
	writeStateFile(t, dir, "nodes.json", `{"version":1,"token":"T","nodes":[
  {"id":1,"type":"vless","enabled":true,"server":{"listen":"0.0.0.0","port":443}},
  {"id":2,"type":"hy2","enabled":true,"server":{"listen":"0.0.0.0","port":44311}},
  {"id":3,"type":"both","enabled":true,"server":{"listen":"0.0.0.0","port":8443}}
]}`)
	writeStateFile(t, dir, "users.json", `{"version":1,"users":[]}`)
	s, err := NewStore(dir)
	if err != nil {
		t.Fatal(err)
	}
	e1, _ := s.lookupNode(1)
	e2, _ := s.lookupNode(2)
	e3, _ := s.lookupNode(3)
	if e1.TLS.PrivateKey == "" || e3.TLS.PrivateKey == "" {
		t.Fatal("vless/both nodes must get Reality keypairs")
	}
	if e2.TLS.PrivateKey != "" || e2.TLS.PublicKey != "" {
		t.Fatal("hy2 node must not get Reality keys")
	}
	// Persisted for all nodes.
	var nf NodesFile
	raw, _ := os.ReadFile(filepath.Join(dir, "nodes.json"))
	if err := json.Unmarshal(raw, &nf); err != nil {
		t.Fatal(err)
	}
	if nf.Nodes[0].TLS.PrivateKey != e1.TLS.PrivateKey || nf.Nodes[2].TLS.PrivateKey != e3.TLS.PrivateKey {
		t.Fatal("multi-node keypairs not persisted")
	}
}

// G2 matrix 2 for hy2 config: must NOT contain reality keys (protocol shape).
func TestRealityConfigHy2HasNoKeys(t *testing.T) {
	dir := t.TempDir()
	writeStateFile(t, dir, "nodes.json", `{"version":1,"token":"T","nodes":[
  {"id":2,"type":"hy2","enabled":true,"server":{"listen":"0.0.0.0","port":44311}}
]}`)
	writeStateFile(t, dir, "users.json", `{"version":1,"users":[]}`)
	s, err := NewStore(dir)
	if err != nil {
		t.Fatal(err)
	}
	e := newAPIEnv(t, s)
	resp, body := e.get(t, "/api/v1/server/UniProxy/config", "T", "2", "hysteria")
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("status = %d body=%s", resp.StatusCode, body)
	}
	if _, ok := bodyContainsKey(body); ok {
		t.Fatalf("hy2 config must not contain reality keys: %s", body)
	}
}

func bodyContainsKey(body []byte) (string, bool) {
	var cfg map[string]any
	if err := json.Unmarshal(body, &cfg); err != nil {
		return "", false
	}
	ts, ok := cfg["tls_settings"].(map[string]any)
	if !ok {
		return "", false
	}
	if k, ok := ts["private_key"].(string); ok && k != "" {
		return "private_key", true
	}
	if k, ok := ts["public_key"].(string); ok && k != "" {
		return "public_key", true
	}
	return "", false
}
